//! Portable oracle fixtures. Expectations follow asap7_drm_201207a.pdf, not
//! either checker's output. All coordinates below are nm on the 0.25 nm grid.
use crate::helpers::{library, write_gz};
use gds21::{GdsBoundary, GdsElement, GdsPoint, GdsUnits};
use gdscheck::pdk::PdkConfig;
use std::fmt::Write;

const DIR: &str = "tests/data/asap7/generated";
type Shape<'a> = (&'a str, [f64; 4]);

struct Corpus<'a> {
    pdk: &'a PdkConfig,
    manifest: String,
}

impl Corpus<'_> {
    fn layout(&mut self, name: &str, shapes: &[Shape<'_>], origin: f64) {
        let elems = shapes
            .iter()
            .map(|(layer, [x0, y0, x1, y1])| {
                let l = self.pdk.layer(layer).unwrap();
                let point = |x: f64, y: f64| {
                    GdsPoint::new(
                        ((origin + x) * 4.0).round() as i32,
                        ((origin + y) * 4.0).round() as i32,
                    )
                };
                GdsElement::GdsBoundary(GdsBoundary {
                    layer: l.gds_layer as i16,
                    datatype: l.gds_datatype as i16,
                    xy: vec![
                        point(*x0, *y0),
                        point(*x1, *y0),
                        point(*x1, *y1),
                        point(*x0, *y1),
                        point(*x0, *y0),
                    ],
                    ..Default::default()
                })
            })
            .collect();
        let mut lib = library("TOP", elems);
        lib.units = GdsUnits(0.00025, 0.25e-9);
        write_gz(&format!("{DIR}/{name}.gds.gz"), lib);
    }

    fn expect(&mut self, name: &str, rule: &str, bad: bool, reason: &str) {
        writeln!(
            self.manifest,
            "{name}\t{rule}\t{}\t{reason}",
            if bad { "fail" } else { "pass" }
        )
        .unwrap();
    }
}

pub fn generate(pdk: &PdkConfig) {
    std::fs::create_dir_all(DIR).unwrap();
    let mut c = Corpus {
        pdk,
        manifest: String::from(
            "# SPDX-FileCopyrightText: 2026 aesc silicon\n# SPDX-License-Identifier: AGPL-3.0-or-later\n\
         # Generated by gen/asap7.rs; case, rule, manual verdict, reason (tab separated).\n",
        ),
    };

    // DRM 3.5: the entire ACTIVE polygon gets SRAM rules when it interacts
    // with SRAMDRC. Crossing the marker must not clip it into two rule regions.
    for mode in ["outside", "inside", "crossing"] {
        for (kind, normal, sram) in [
            ("space", "ACTIVE.WELL.S.4", "SRAM.ACTIVE.WELL.S.5"),
            ("enclosure", "ACTIVE.WELL.EN.1", "SRAM.ACTIVE.WELL.EN.2"),
        ] {
            for margin in [13.25, 13.5, 13.75, 26.75, 27.0, 27.25] {
                let name = format!("active_{kind}_{mode}_{}", (margin * 4.0) as i32);
                let well = if kind == "space" {
                    [32.0 + margin, -100.0, 232.0 + margin, 200.0]
                } else {
                    [-margin, -margin, 32.0 + margin, 27.0 + margin]
                };
                let mut shapes = vec![
                    ("ACTIVE", [0.0, 0.0, 32.0, 27.0]),
                    ("NSELECT", [-100.0, -100.0, 300.0, 300.0]),
                    ("NWELL", well),
                ];
                let marker = match mode {
                    "inside" => [-200.0, -200.0, 400.0, 400.0],
                    "crossing" => [16.0, -200.0, 400.0, 400.0],
                    _ => [500.0, -200.0, 600.0, 400.0],
                };
                shapes.push(("SRAMDRC", marker));
                c.layout(&name, &shapes, 6990.0);
                c.expect(
                    &name,
                    normal,
                    mode == "outside" && margin < 27.0,
                    "DRM 3.5: non-SRAM ACTIVE uses 27 nm; interacting polygons are exempt",
                );
                c.expect(
                    &name,
                    sram,
                    mode != "outside" && margin < 13.5,
                    "DRM 3.5: whole interacting ACTIVE polygon uses 13.5 nm",
                );
            }
        }
    }

    // DRM 3.7: minimum vertical SDT overlap with ACTIVE in SRAM is 17 nm.
    for overlap in [16.75, 17.0, 17.25] {
        let name = format!("sdt_overlap_{}", (overlap * 4.0) as i32);
        c.layout(
            &name,
            &[
                ("SDT", [0.0, 0.0, 24.0, 27.0]),
                ("ACTIVE", [-10.0, 27.0 - overlap, 40.0, 54.0 - overlap]),
                ("LISD", [-5.0, -5.0, 30.0, 60.0]),
                ("SRAMDRC", [-20.0, -20.0, 70.0, 70.0]),
            ],
            19990.0,
        );
        c.expect(
            &name,
            "SRAM.SDT.ACTIVE.OV.3",
            overlap < 17.0,
            "DRM 3.7: vertical overlap >= 17 nm",
        );
    }

    // DRM 3.11: the 5 nm and 2 nm margins must be on the SAME opposite pair.
    for (name, margins, bad) in [
        ("v1_split_axes", [5.0, 0.0, 2.0, 2.0], true),
        ("v1_small_under", [5.0, 1.75, 0.0, 0.0], true),
        ("v1_large_under", [4.75, 2.0, 0.0, 0.0], true),
        ("v1_exact", [5.0, 2.0, 0.0, 0.0], false),
        ("v1_over", [5.25, 2.25, 0.0, 0.0], false),
        ("v1_rotated", [0.0, 0.0, 2.0, 5.0], false),
    ] {
        let [l, r, b, t] = margins;
        c.layout(
            name,
            &[
                ("V1", [0.0, 0.0, 18.0, 18.0]),
                ("M1", [-l, -b, 18.0 + r, 18.0 + t]),
                ("M2", [0.0, -5.0, 18.0, 23.0]),
            ],
            19990.0,
        );
        c.expect(
            name,
            "V1.M1.EN.1",
            bad,
            "DRM 3.11: 5/2 nm on the same opposite pair",
        );
    }

    for width in [23.75, 24.0, 24.25] {
        let name = format!("m4_width_{}", (width * 4.0) as i32);
        c.layout(&name, &[("M4", [0.0, 0.0, 100.0, width])], 6990.0);
        c.expect(
            &name,
            "M4.W.1",
            width < 24.0,
            "DRM 3.14: M4 vertical width >= 24 nm",
        );
    }
    for width in [59.75, 60.0, 60.25] {
        let name = format!("m8_long_width_{}", (width * 4.0) as i32);
        c.layout(&name, &[("M8", [0.0, 0.0, 400.0, width])], 19990.0);
        c.expect(
            &name,
            "M8.W.2",
            width < 60.0,
            "DRM 3.18: 400 nm long M8 needs width >= 60 nm",
        );
    }

    // Three routed nets exercise all upper metals M4-M9 and V4/V6/V8.
    // The defective companion shortens one M9 end to give V8 only 19.75 nm.
    for bad in [false, true] {
        let name = if bad { "routed_bad" } else { "routed_clean" };
        c.layout(
            name,
            &[
                ("M4", [-100.0, -12.0, 100.0, 12.0]),
                ("M5", [-12.0, -100.0, 12.0, 100.0]),
                ("V4", [-12.0, -12.0, 12.0, 12.0]),
                ("M6", [900.0, -16.0, 1100.0, 16.0]),
                ("M7", [984.0, -100.0, 1016.0, 100.0]),
                ("V6", [984.0, -16.0, 1016.0, 16.0]),
                ("M8", [1900.0, -30.0, 2100.0, 30.0]),
                (
                    "M9",
                    [1970.0, -100.0, 2030.0, if bad { 39.75 } else { 100.0 }],
                ),
                ("V8", [1980.0, -20.0, 2020.0, 20.0]),
            ],
            19990.0,
        );
        c.expect(
            name,
            "V8.M9.EN.2",
            bad,
            "DRM 3.19: V8 needs 20 nm M9 enclosure on opposite sides",
        );
    }
    std::fs::write(format!("{DIR}/cases.tsv"), c.manifest).unwrap();
}
